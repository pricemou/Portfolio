def get_lang(request):
    lang = request.cookies.get('lang') or request.args.get('lang')
    if lang in TRANSLATIONS:
        return lang
    return 'fr'


def translate(key, lang='fr'):
    table = TRANSLATIONS.get(lang) or TRANSLATIONS['fr']
    return table.get(key) or TRANSLATIONS['fr'].get(key, key)
